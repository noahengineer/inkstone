// glyphs keep, because the screen would read differently without them:
//  - digits and capitals use all 9 rows; lower case has a 7-row x-height and no descenders (the
//    tails of g, p, q, y are squeezed into the cell, as the measured captures show);
//  - `−` (subtraction) is a 5-dot bar and `-` (the (−) key) a 3-dot bar in columns 1–3, both on the
