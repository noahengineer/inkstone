private const val SUPERSCRIPTS = "⁰¹²³⁴⁵⁶⁷⁸⁹"
private const val SUBSCRIPTS = "₀₁₂₃₄₅₆₇₈₉"

/**
 * Raised and lowered marks are the small font's own glyphs placed in the large cell: a superscript
 * on rows 1–6 of the cell, a subscript sitting on the baseline (rows 4–9), which is exactly how
 * research 01 §3.6 measures `X₁=` on a ZA screen.
 */
private fun largeScripts(): List<Pair<String, List<String>>> {
    val small = LcdFont.SMALL
    fun script(key: String, top: Int) = placed(small.rowsOf(key), LcdFont.FULL_INK, LcdFont.LARGE_HEIGHT, top)
    val raised = SUPERSCRIPTS.mapIndexed { digit, mark -> mark.toString() to script(digit.toString(), 0) }
    val lowered = SUBSCRIPTS.mapIndexed { digit, mark ->
        mark.toString() to script(digit.toString(), LARGE_SUBSCRIPT_TOP)
    }
    return raised + lowered + ("ₙ" to script("n", LARGE_SUBSCRIPT_TOP))
}

private const val LARGE_SUBSCRIPT_TOP = 3

internal fun largeGlyphs(): List<Pair<String, List<String>>> =
    LARGE_DIGITS + LARGE_UPPER + LARGE_LOWER + LARGE_PUNCTUATION + LARGE_OPERATORS + LARGE_MARKERS +
        LARGE_GREEK + largeScripts()
