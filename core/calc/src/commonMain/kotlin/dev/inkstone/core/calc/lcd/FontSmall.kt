private const val SMALL_SUPERSCRIPTS = "⁰¹²³⁴⁵⁶⁷⁸⁹"
private const val SMALL_SUBSCRIPTS = "₀₁₂₃₄₅₆₇₈₉"

/** Raised and lowered digits in the small font are the tiny font's, placed as the large ones are. */
private fun smallScripts(): List<Pair<String, List<String>>> {
    val tiny = LcdFont.TINY
    fun script(key: String, top: Int) = placed(tiny.rowsOf(key), LcdFont.FULL_INK, LcdFont.SMALL_HEIGHT, top)
    val raised = SMALL_SUPERSCRIPTS.mapIndexed { digit, mark -> mark.toString() to script(digit.toString(), 0) }
    val lowered = SMALL_SUBSCRIPTS.mapIndexed { digit, mark -> mark.toString() to script(digit.toString(), 1) }
    return raised + lowered + ("ₙ" to script("n", 1))
}

internal fun smallGlyphs(): List<Pair<String, List<String>>> =
    SMALL_DIGITS + SMALL_UPPER + SMALL_LOWER + SMALL_PUNCTUATION + SMALL_OPERATORS + SMALL_MARKERS +
        SMALL_GREEK + smallScripts()
