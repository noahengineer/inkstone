package dev.inkstone.core.calc.parse

/**
 * Every input in research 04 (COMP, general) and 05 (modes) that is typed on the calculation line,
 * with the keys as the guide prints them (the trailing `=` dropped — evaluation is not this
 * layer's job). [linear] is the line as [dev.inkstone.core.calc.input.linearText] spells it, which
 * spells templates the LineIO way: the guide's `Pol(√2;√2)` is `Pol(√(2);√(2))` here. [tree] pins
 * the parse where the vector exercises a priority or a template.
 *
 * Inputs that only happen inside editors (STAT, EQN, MATRIX cells, TABLE prompts) are not here;
 * TABLE's f(X) is, because it is typed on a line.
 */
private fun line(id: String, keys: String, linear: String, tree: String? = null) =
    Vector(id, keys, linear, tree, natural = false)

