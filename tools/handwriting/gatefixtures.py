"""Ink for the instrumented ML Kit gate test (docs/HANDWRITING-SYNTHESIS.md §11, H6).

    .venv/Scripts/python -I gatefixtures.py

writes `app/src/androidTest/assets/handwriting/gate-fixtures.json`: a few words, numbers and their
look-alikes, each written by two of synth.py's synthetic writers -- licensed single-line fonts
animated by the sigma-lognormal model, the same writers the shipped model was trained on (§7.2).

Why synthetic ink, and not the user's: the gate test must run on any device and be committed, and
the user's handwriting is never committed (§9). Why not the shipped model's ink: the test is about
the gate, and a witness written by the model it sits behind would move whenever the model does.

The file carries every font's licence, attribution and SHA-256, exactly as a corpus manifest does,
so it is as clean as the corpus (D13). It is test data: nothing ships it, and nothing trains on it.
"""

from __future__ import annotations

import argparse
import json
import os
import random
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)

import synth  # noqa: E402

FORMAT = "inkstone-gate-fixtures-1"
OUT = os.path.join(HERE, "..", "..", "app", "src", "androidTest", "assets", "handwriting", "gate-fixtures.json")

# Ordinary words: the positive control, and each other's wrong labels for the negative one.
WORDS = [
    "minute", "salt", "water", "energy", "graph", "notes", "write", "cation", "copper", "light",
    "force", "metal", "plant", "river", "table", "house", "paper", "music", "green", "seven",
]
# Numbers, and the same digits with the point gone: §18.10's vanished decimal point, both ways.
NUMBERS = ["2.5", "25", "9.81", "981", "3.14", "314", "12.875", "12875", "0.25", "46", "1.625", "1625"]
# How many synthetic writers write each text, each in a different face.
WRITERS_PER_TEXT = 2
DECIMALS = 4


def writers_by_face(faces: dict, seed: int) -> list[synth.Writer]:
    """The first writer of every face, in face order, so the fixture covers every licensed font."""
    found: dict[str, synth.Writer] = {}
    writer_id = 0
    while len(found) < len(faces) and writer_id < 10_000:
        w = synth.make_writer(writer_id, faces, seed)
        found.setdefault(w.font, w)
        writer_id += 1
    return [found[f] for f in sorted(found)]


def strokes_of(sample: synth.Sample) -> list[list[float]]:
    """The sample's pen-downs as flat [x0, y0, x1, y1, ...] lists, in x-heights, y up."""
    strokes, current = [], []
    for (x, y), end in zip(sample.xy.tolist(), sample.eos.tolist()):
        current += [round(float(x), DECIMALS), round(float(y), DECIMALS)]
        if end:
            strokes.append(current)
            current = []
    if current:
        strokes.append(current)
    return strokes


def generate(seed: int) -> dict:
    faces = synth._faces()
    writers = writers_by_face(faces, seed)
    samples = []
    for i, text in enumerate(WORDS + NUMBERS):
        for k in range(WRITERS_PER_TEXT):
            w = writers[(i + k * (len(writers) // WRITERS_PER_TEXT + 1)) % len(writers)]
            rng = random.Random(seed * 7_919 + w.id * 1_000 + i)
            sample = synth.write_sample(text, w, rng)
            if sample is None or len(sample.xy) < 4:
                raise SystemExit(f"writer {w.id} ({w.font}) could not write {text!r}")
            samples.append({"text": text, "writer": w.id, "font": w.font, "strokes": strokes_of(sample)})
    used = sorted({s["font"] for s in samples})
    return {
        "format": FORMAT,
        "licence": synth.CORPUS_LICENCE,
        "licence_note": "Generated by tools/handwriting/gatefixtures.py from the fonts below; no third-party "
                        "handwriting, and none of the user's. Test data: never shipped, never trained on.",
        "frame": "x-heights, y up, baseline 0, deslanted (NormalFrame, docs/HANDWRITING-SYNTHESIS.md §5.2)",
        "seed": seed,
        "generator": {"git": synth.git_sha(), "script": "tools/handwriting/gatefixtures.py"},
        "sources": [
            {k: getattr(faces[i].entry, k) for k in ("id", "licence", "sha256", "source", "attribution")}
            for i in used
        ],
        "words": WORDS,
        "numbers": NUMBERS,
        "samples": samples,
    }


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--seed", type=int, default=6)
    ap.add_argument("--out", default=OUT)
    a = ap.parse_args(argv)
    fixtures = generate(a.seed)
    os.makedirs(os.path.dirname(os.path.abspath(a.out)), exist_ok=True)
    with open(a.out, "w", encoding="utf-8", newline="\n") as f:
        json.dump(fixtures, f, separators=(",", ":"), ensure_ascii=True)
        f.write("\n")
    fonts = sorted({s["font"] for s in fixtures["samples"]})
    print(f"{len(fixtures['samples'])} samples in {len(fonts)} faces -> {os.path.normpath(a.out)}")


if __name__ == "__main__":
    main()
